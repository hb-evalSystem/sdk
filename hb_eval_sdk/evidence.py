"""
hb_eval_sdk.evidence — the runtime evidence model
==================================================

WHY THIS MODULE EXISTS, AND WHY IT COMES BEFORE THE INJECTOR
An earlier draft of fault injection wrote its provenance onto the monitoring
session:

    session._field_sources["had_fault"] = "runtime_observed"

The agent holds that session. It can overwrite the field. So the label saying
"the system observed this" lived somewhere the measured party could edit —
the exact failure the provenance rules exist to prevent, breaking a rule this
project had already established:

    A provenance label the subject can set is not provenance.

This module is the correction. Evidence lives in a store the agent is never
handed, and the label is produced by the instrumentation path rather than
accepted from a caller.

THREE STATES, NEVER COLLAPSED
A boolean `had_fault` destroys the distinction between three situations:

    intended    what the fault plan asked for
    injected    whether the injector actually applied it
    observed    what the runtime actually saw happen

They come apart in practice. A plan can request a timeout, the injector can
fail to apply it, and the call can return normally. Recording that as
`had_fault = True` manufactures evidence for a fault that never occurred.

The three are stored separately and the boolean is DERIVED, with the
derivation refusing to claim a fault the runtime did not observe.

WHAT "runtime_observed" MEANS HERE, PRECISELY
Not "true". It means: evidence generated by the instrumentation boundary
rather than reported by the agent.

The instrumentation runs in the same Python process as the agent, and a
process is not a security boundary against code running inside it. What this
design prevents is the agent SUPPLYING provenance, and accidental corruption
of the record. It does not prevent deliberate tampering by code that goes
looking, and no in-process design can.
"""
from __future__ import annotations

import time
import uuid
import weakref
from dataclasses import asdict, dataclass
from typing import Optional

# NOTE: this module's public surface is intentionally NOT re-exported from
# hb_eval_sdk's top-level __init__.py. It is reachable only via
# `hb_eval_sdk.evidence`, which is a deliberate step away from the advertised
# API — the agent-facing contract is `hb_eval_sdk.fault_context` and friends,
# not this. See RuntimeEvidenceStore's docstring for what that does and does
# not protect against.
__all__ = [
    "InjectionStatus", "ObservedOutcome", "FaultEvent", "PendingFaultEvent",
    "RuntimeEvidenceStore", "evidence_for_session", "new_event", "seal",
]


class InjectionStatus:
    """Did the injector do what the plan asked?

    APPLIED   applied as specified
    SKIPPED   deliberately not applied — probability gate, or disabled
    FAILED    tried and could not
    PARTIAL   applied differently from the specification
    """
    APPLIED = "applied"
    SKIPPED = "skipped"
    FAILED = "failed"
    PARTIAL = "partial"
    ALL = (APPLIED, SKIPPED, FAILED, PARTIAL)


class ObservedOutcome:
    """What the runtime saw, independent of what was intended.

    NORMAL matters most. It makes "the injection failed and the call
    succeeded" recordable, rather than silently becoming a fault that did not
    happen.
    """
    NORMAL = "normal"
    TIMEOUT = "timeout"
    EXCEPTION = "exception"
    EMPTY = "empty"
    MALFORMED = "malformed"
    DELAYED_SUCCESS = "delayed_success"

    WRONG = "wrong"
    """The call SUCCEEDED and returned structurally valid, semantically false
    data. Distinct from MALFORMED, and the distinction is the whole reason
    this outcome exists: malformed data announces itself by failing to parse,
    while wrong data parses perfectly and is untrue. Nothing raised, nothing
    was empty, and an agent has no signal at all unless it checks."""

    ALL = (NORMAL, TIMEOUT, EXCEPTION, EMPTY, MALFORMED, DELAYED_SUCCESS,
           WRONG)


@dataclass
class PendingFaultEvent:
    """The MUTABLE builder used while a fault is being applied.

    Injection is not atomic: `requested_at` is stamped before the call, and
    `observed_outcome` is not known until after it. Something has to hold
    state across that span, and this is it — deliberately a different type
    from `FaultEvent`, so that what gets STORED can be frozen without making
    the dispatch code that builds it up impossible to write.

    This type is never handed to a caller and never appears in the evidence
    store. It exists only inside faults.py's dispatch functions.
    """
    fault_event_id: str
    session_id: Optional[str]
    step_index: Optional[int]
    tool_invocation_id: str
    fault_plan_id: Optional[str]

    target: str
    intended_type: str
    intended_params: dict

    injection_status: str = "skipped"
    injection_note: str = ""

    observed_outcome: str = "normal"
    exception_type: Optional[str] = None
    http_status: Optional[int] = None
    response_shape: Optional[str] = None

    requested_at: float = 0.0
    started_at: float = 0.0
    ended_at: float = 0.0

    seed: Optional[int] = None
    attempt_index: int = 0

    cascade_id: Optional[str] = None
    cascade_stage_index: Optional[int] = None

    # These three are needed on the PENDING event too, not only the sealed
    # one: `_dispatch_cascade` must know whether a stage fired — via
    # `fault_present` — BEFORE the event is sealed, in order to decide
    # whether to arm the next stage. Duplicated rather than shared through a
    # mixin, because dataclass + mixin property resolution order is a common
    # source of subtle bugs, and these three are short enough that keeping
    # them in sync by hand is the more legible choice.
    @property
    def duration_ms(self) -> float:
        """Elapsed milliseconds between start and end, or 0.0 if either was not recorded."""
        if not (self.started_at and self.ended_at):
            return 0.0
        return round((self.ended_at - self.started_at) * 1000, 3)

    @property
    def fault_present(self) -> bool:
        """True only if the fault was actually applied and the observed outcome was not normal. A fault that was planned but skipped, or applied without effect, is not present."""
        return (self.injection_status == InjectionStatus.APPLIED
                and self.observed_outcome != ObservedOutcome.NORMAL)

    @property
    def matched_intent(self) -> bool:
        """True if what was observed is what the injected fault mode is expected to produce (a timeout fault yielding a timeout, a latency fault a delayed success, and so on)."""
        expected = {
            "timeout": ObservedOutcome.TIMEOUT,
            "latency": ObservedOutcome.DELAYED_SUCCESS,
            "error_5xx": ObservedOutcome.EXCEPTION,
            "connection_refused": ObservedOutcome.EXCEPTION,
            "intermittent": ObservedOutcome.EXCEPTION,
            "empty_response": ObservedOutcome.EMPTY,
            "malformed": ObservedOutcome.MALFORMED,
            "tool_exception": ObservedOutcome.EXCEPTION,
            # The OUTPUT/STATE family all manifest as WRONG: the call
            # succeeded and returned false data. They differ in HOW the data
            # is false, which response_shape records, not in what the runtime
            # observed.
            "wrong_response": ObservedOutcome.WRONG,
            "stale_context": ObservedOutcome.WRONG,
            "contradictory_context": ObservedOutcome.WRONG,
            "corrupted_result": ObservedOutcome.WRONG,
            "memory_contamination": ObservedOutcome.WRONG,
        }.get(self.intended_type)
        return expected is not None and self.observed_outcome == expected


@dataclass(frozen=True)
class FaultEvent:
    """One attempt to inject a fault, and what came of it — IMMUTABLE.

    Identity fields exist so a metric can be traced back to the execution
    event that produced it. Without them you know a fault occurred; you
    cannot show which tool call it affected or which agent step followed.

    FROZEN DELIBERATELY. An earlier version of this class was a plain
    mutable dataclass, and `store.events` returned a tuple wrapping
    references to the live objects — a tuple you cannot append to, holding
    objects you very much CAN mutate. Any code in the process that reached
    the store (which, before this fix, included a public top-level import)
    could do:

        event.observed_outcome = "normal"      # hide that a fault occurred
        event.injection_status = "applied"     # claim success that never happened

    Freezing closes that: once a FaultEvent exists, `event.field = x` raises
    `dataclasses.FrozenInstanceError`. Evidence, once committed, does not
    change — which is the property "runtime_observed" is supposed to promise
    and previously did not enforce.

    Constructed exactly once, by `seal()`, from a completed
    `PendingFaultEvent`. Nothing else should construct one directly outside
    tests that are deliberately probing this boundary.
    """

    fault_event_id: str
    session_id: Optional[str]
    step_index: Optional[int]
    tool_invocation_id: str
    fault_plan_id: Optional[str]

    target: str
    intended_type: str
    intended_params: dict

    injection_status: str
    injection_note: str = ""

    observed_outcome: str = ObservedOutcome.NORMAL
    exception_type: Optional[str] = None
    http_status: Optional[int] = None
    response_shape: Optional[str] = None

    requested_at: float = 0.0
    started_at: float = 0.0
    ended_at: float = 0.0

    seed: Optional[int] = None
    attempt_index: int = 0

    # Set only for events produced inside a cascade topology. None for
    # ordinary fault_context events — a plain timeout on one tool has no
    # "stage" because it belongs to no chain.
    cascade_id: Optional[str] = None
    cascade_stage_index: Optional[int] = None

    @property
    def duration_ms(self) -> float:
        """Elapsed milliseconds between start and end, or 0.0 if either was not recorded."""
        if not (self.started_at and self.ended_at):
            return 0.0
        return round((self.ended_at - self.started_at) * 1000, 3)

    @property
    def fault_present(self) -> bool:
        """Whether a fault actually occurred — DERIVED, not asserted.

        A fault is present only when it was applied AND the runtime observed
        something other than a normal outcome. An injection that failed, or one
        the runtime shrugged off, is not a fault the agent had to handle, and
        counting it would credit the agent for surviving something that never
        happened to it.
        """
        return (self.injection_status == InjectionStatus.APPLIED
                and self.observed_outcome != ObservedOutcome.NORMAL)

    @property
    def matched_intent(self) -> bool:
        """Did the runtime outcome match what was intended?

        A plan asking for a 5xx and a runtime raising a connection error is an
        injection that applied and manifested differently. Worth recording
        rather than reporting as "5xx observed": a study claiming to test 5xx
        handling should not quietly include connection failures.
        """
        expected = {
            "timeout": ObservedOutcome.TIMEOUT,
            "latency": ObservedOutcome.DELAYED_SUCCESS,
            "error_5xx": ObservedOutcome.EXCEPTION,
            "connection_refused": ObservedOutcome.EXCEPTION,
            "intermittent": ObservedOutcome.EXCEPTION,
            "empty_response": ObservedOutcome.EMPTY,
            "malformed": ObservedOutcome.MALFORMED,
            "tool_exception": ObservedOutcome.EXCEPTION,
            # The OUTPUT/STATE family all manifest as WRONG: the call
            # succeeded and returned false data. They differ in HOW the data
            # is false, which response_shape records, not in what the runtime
            # observed.
            "wrong_response": ObservedOutcome.WRONG,
            "stale_context": ObservedOutcome.WRONG,
            "contradictory_context": ObservedOutcome.WRONG,
            "corrupted_result": ObservedOutcome.WRONG,
            "memory_contamination": ObservedOutcome.WRONG,
        }.get(self.intended_type)
        return expected is not None and self.observed_outcome == expected

    def to_dict(self) -> dict:
        """The JSON-serialisable form, with `duration_ms`, `fault_present`, `matched_intent` and a provenance block stating that the instrumentation boundary, not the agent, generated the event."""
        d = asdict(self)
        d["duration_ms"] = self.duration_ms
        d["fault_present"] = self.fault_present
        d["matched_intent"] = self.matched_intent
        d["provenance"] = {
            "source": "runtime_observed",
            "meaning": ("generated by the instrumentation boundary, not "
                        "reported by the agent"),
            "limit": ("the instrumentation shares a process with the agent; "
                      "this is not a security boundary against code running "
                      "inside it"),
        }
        return d


# A private sentinel. `faults.py` obtains this at import time and passes it
# into every `record()` call; nothing else in the package holds a reference to
# it, and it is not exported from `hb_eval_sdk`. Possessing the exact object
# (not a string, not a guessable value — the object identity itself) is what
# `record()` checks.
#
# This is not cryptography and does not claim to be. It is friction: an
# agent's code, running in the same process, CAN in principle walk the module
# graph and find this object if it goes looking (`faults._INSTRUMENTATION_TOKEN`
# is not hidden from introspection — nothing in Python is). What it stops is
# the direct, obvious path: constructing a FaultEvent-shaped payload and
# calling `store.record(it)`. That already closes the casual and accidental
# cases entirely, and the honest limit is stated here rather than implied.
_INSTRUMENTATION_TOKEN = object()


def _instrumentation_token():
    """Called once by faults.py to obtain the gate token.

    A function rather than a bare module attribute so the intent is explicit
    at the call site: `evidence._instrumentation_token()` reads as "I am the
    trusted dispatch path asking for permission to write," not as a constant
    anyone importing the module happens to see first.
    """
    return _INSTRUMENTATION_TOKEN


# Backing storage for every store's events, keyed by id(store) rather than
# held as an instance attribute — see RuntimeEvidenceStore's __slots__ note
# for why. Cleaned up via weakref.finalize when a store is garbage collected.
_event_backing: dict = {}


class RuntimeEvidenceStore:
    """Where fault evidence lives.

    THREE LAYERS, EACH CLOSING A DIFFERENT VECTOR
    An earlier version of this store made one claim — "not reachable from the
    session" — and that claim was true and insufficient: it did not check
    whether the STORED EVENTS could be mutated after commit (they could — a
    plain mutable dataclass), or whether a caller with no legitimate connection
    to the instrumentation could inject a FABRICATED event via `record()`
    (they could — no gate existed). Both were found by testing the actual
    attack, not by re-reading the design.

    1. Committed events are FROZEN (`FaultEvent` is `frozen=True`). Once
       recorded, `event.field = x` raises. This is the substantive fix: it
       means even code that reaches a real, legitimately-recorded event
       cannot alter it.

    2. `record()` requires the instrumentation token — obtainable only by
       code that imports the sentinel from `faults.py`'s trusted dispatch
       path. This raises the bar against fabricating an entirely new event
       and injecting it; it is friction, not a proof, and is described as
       such above.

    3. Not exported from the package's public surface (`hb_eval_sdk.__init__`
       does not expose this class or the registry function). The agent is
       handed a MonitorSession, never this.

    None of the three is a security boundary against a determined adversary
    with full reflection access to the same Python process — no in-process
    design is. Together they mean: a caller that does not go looking cannot
    reach this at all, and a caller that DOES go looking can read the record
    but cannot alter what a real event says happened, and cannot get a forged
    event accepted without also finding and importing the trusted sentinel.
    """

    # NOTE: no "_events" slot. The actual list lives in a module-private dict
    # keyed by id(self), not as an attribute on the instance at all — see
    # `_event_backing` below. An earlier version stored the list directly as
    # `self._events`, and __slots__ turned out to protect against adding NEW
    # attributes, not against code holding a reference to `store` calling
    # `store._events.clear()` on the EXISTING list attribute. That was
    # security finding [5]: evidence could be deleted by any code that
    # reached the store object. Removing the attribute entirely closes the
    # obvious version of that vector.
    __slots__ = ("_session_id", "_frozen", "__weakref__")

    def __init__(self, session_id: Optional[str] = None):
        self._session_id = session_id
        self._frozen = False
        _event_backing[id(self)] = []
        weakref.finalize(self, _event_backing.pop, id(self), None)

    def record(self, event: FaultEvent, _token=None) -> None:
        """Append a fault event. Only the instrumentation in `faults.py` holds the token this requires; any other caller gets a PermissionError, so agent code cannot write its own evidence."""
        if _token is not _INSTRUMENTATION_TOKEN:
            # Rejected without saying why beyond this. A caller that does not
            # already hold the token from faults.py has no legitimate reason
            # to be calling this, and a detailed error would only help someone
            # find the right token to forge past this check.
            raise PermissionError(
                "record() requires the instrumentation token; evidence can "
                "only be committed by the fault injection dispatch path")
        if not isinstance(event, FaultEvent):
            # Belt and suspenders: even holding the token, only a genuinely
            # sealed, frozen FaultEvent is accepted — a PendingFaultEvent or
            # any other object is rejected here rather than silently stored.
            raise TypeError(
                f"record() requires a sealed FaultEvent, got "
                f"{type(event).__name__}. Call seal() first.")
        if self._frozen:
            # Append-only, and closed once. A log that accepts entries after
            # the session ended cannot be read chronologically, and a reader
            # has no way to detect that it was appended to.
            raise RuntimeError(
                "this evidence store is closed; the session has ended")
        _event_backing[id(self)].append(event)

    def freeze(self) -> None:
        """Stop accepting events. Nothing in this package calls it automatically: a caller that needs a session's evidence to be final must freeze the store itself."""
        self._frozen = True

    @property
    def events(self) -> tuple:
        """A tuple, not the list. Callers cannot append through this, and
        there is no `._events` attribute on this object to reach in the
        first place — see the class docstring's three-layer note."""
        return tuple(_event_backing.get(id(self), ()))

    def fault_episodes(self) -> int:
        """Distinct fault episodes, not faulted calls.

        Consecutive events on the same target are one episode: the agent had
        one problem to adapt to, not three. Same rule PEI applies to steps,
        kept consistent so the two cannot disagree.
        """
        episodes, previous = 0, None
        for e in self.events:
            if not e.fault_present:
                previous = None
                continue
            if e.target != previous:
                episodes += 1
            previous = e.target
        return episodes

    def cascade_topology(self, cascade_id: str,
                         total_stages: Optional[int] = None) -> dict:
        """Did a cascade's stages fire in the order the topology specified?

        `total_stages` is the number of stages the PLAN defines, not the
        number that were attempted — this must come from the caller, because
        the evidence store only knows what happened, and "did the agent reach
        the end of the topology" is a question about what happened relative
        to what the topology promised.

        An earlier version compared the last fired stage against the highest
        stage index seen in the events, which is wrong: if the agent only
        ever touches stage 0, that IS the highest index seen, and the
        comparison passes vacuously — reporting a fallback as reached when
        the fallback was never attempted. Caught by a test that specifically
        checked the "agent never calls the backup" case.

        Returns which stage indices actually fired, in what order, and
        whether the final DEFINED stage fired — not merely the final stage
        that happened to be attempted.
        """
        events = [e for e in self.events if e.cascade_id == cascade_id]
        events.sort(key=lambda e: e.requested_at)
        fired_stages = [e.cascade_stage_index for e in events if e.fault_present]
        in_order = fired_stages == sorted(set(fired_stages))

        if total_stages is not None:
            reached_final = bool(fired_stages) and (total_stages - 1) in fired_stages
        else:
            # No plan size given: can only say whether SOMETHING fired, which
            # is a weaker claim and is reported as such by callers that check
            # this branch.
            reached_final = None

        return {
            "cascade_id": cascade_id,
            "events_in_chain": len(events),
            "stages_fired": fired_stages,
            "fired_in_ascending_order": in_order,
            "reached_final_stage": reached_final,
        }

    def summary(self) -> dict:
        """Counts for the session: events recorded, injections applied, skipped and failed, faults actually present, fault episodes, and applied injections whose observed outcome did not match the intended mode."""
        applied = [e for e in self.events
                   if e.injection_status == InjectionStatus.APPLIED]
        mismatched = [e for e in applied if not e.matched_intent]
        return {
            "session_id": self._session_id,
            "events_recorded": len(self.events),
            "injections_applied": len(applied),
            "injections_skipped": sum(
                1 for e in self.events
                if e.injection_status == InjectionStatus.SKIPPED),
            "injections_failed": sum(
                1 for e in self.events
                if e.injection_status == InjectionStatus.FAILED),
            "faults_present": sum(1 for e in self.events if e.fault_present),
            "fault_episodes": self.fault_episodes(),
            # Applied but manifesting differently than intended. Non-zero means
            # the study tested something adjacent to what it planned.
            "intent_mismatches": len(mismatched),
            "source": "runtime_observed",
        }

    def to_dict(self) -> dict:
        """The JSON-serialisable form: the summary and every recorded event."""
        return {"summary": self.summary(),
                "events": [e.to_dict() for e in self.events]}


# ═══════════════════════════════════════════════════════════════════════
#  TWO SEPARATE REGISTRIES — DELIBERATELY NOT ONE
# ═══════════════════════════════════════════════════════════════════════
#
# Security testing found that a single string-keyed registry lets any code
# holding a session_id STRING — which is a plain UUID, not a secret, and is
# routinely visible in logs, error messages, or simply on the session object
# an agent legitimately holds — reach the evidence store for ANY session by
# guessing or recalling that string. That is finding [4] in
# test_fault_injection_security.py, and it was open.
#
# The fix is not cryptographic; it is a change of KEY. Knowing a string is
# cheap. Holding a reference to the exact live Python object that
# `fault_context` was called with is not — an adversary in one session's code
# has no way to obtain another session's object unless the framework hands it
# to them, and it does not.
#
# So there are two registries:
#
#   _stores_by_identity   keyed by id(session_object) — the path
#                         `fault_context` actually uses. Reaching a store here
#                         requires the exact object, not a copy of its id
#                         string.
#
#   _stores_by_label      keyed by a plain string — for tests and
#                         introspection with no session object at hand. NOT
#                         used by the trusted dispatch path, and NOT the same
#                         keyspace: guessing a session's id string reaches
#                         nothing real here, because real evidence was never
#                         written into this registry for that session.
#
# `weakref.finalize` cleans up the identity registry when a session object is
# garbage collected, which also avoids `id()` reuse after collection turning
# into an accidental collision with a future, unrelated session.
_stores_by_identity: dict = {}
_stores_by_label: dict = {}


def evidence_for(session_obj, create: bool = True):
    """The strong lookup path: keyed by the session object's identity.

    This is what `fault_context` uses internally. Two different session
    objects that happen to carry the same `.session_id` string get two
    different, unrelated stores here — because they are different objects,
    and object identity, not a copied string, is the key.
    """
    if session_obj is None:
        return evidence_for_session(None, create=create)

    key = id(session_obj)
    store = _stores_by_identity.get(key)
    if store is None and create:
        label = getattr(session_obj, "session_id", None)
        store = RuntimeEvidenceStore(label)
        _stores_by_identity[key] = store
        # Remove the entry when the session object is collected, so a later,
        # unrelated object that happens to be allocated at the same memory
        # address (and therefore the same id()) cannot inherit a stale store.
        weakref.finalize(session_obj, _stores_by_identity.pop, key, None)
    return store


def evidence_for_session(session_id: Optional[str], create: bool = True):
    """The weak lookup path: keyed by a plain string.

    Exists for tests and introspection that have a session_id string but not
    the live session object. THIS IS NOT WHERE REAL EVIDENCE LIVES — the
    trusted dispatch path in faults.py writes through `evidence_for()`, keyed
    by object identity, specifically so that knowing or guessing a
    session_id string does not grant access to it.

    If you are writing a test and want to read back evidence that was
    recorded during a real `fault_context` call, keep the session OBJECT
    around and call `evidence_for(session_obj, ...)`, not this.
    """
    key = session_id or "_default"
    store = _stores_by_label.get(key)
    if store is None and create:
        store = RuntimeEvidenceStore(session_id)
        _stores_by_label[key] = store
    return store


def new_event(*, target: str, intended_type: str, intended_params: dict,
              session_id: Optional[str] = None,
              step_index: Optional[int] = None,
              fault_plan_id: Optional[str] = None,
              seed: Optional[int] = None,
              attempt_index: int = 0) -> PendingFaultEvent:
    """Open a PENDING event at the moment injection is requested.

    Returns the mutable builder, not the frozen record — the dispatch code in
    faults.py fills in `started_at`, `injection_status`, `observed_outcome`
    and the rest as the call actually happens, and none of that is knowable
    yet at this point. `seal()` converts it to the immutable `FaultEvent` once
    it is complete.

    Created before the call, so `requested_at` is honest: an event stamped
    after the fact cannot distinguish injector overhead from the delay the
    fault itself introduced.
    """
    return PendingFaultEvent(
        fault_event_id=f"FE-{uuid.uuid4().hex[:12]}",
        session_id=session_id,
        step_index=step_index,
        tool_invocation_id=f"TI-{uuid.uuid4().hex[:12]}",
        fault_plan_id=fault_plan_id,
        target=target,
        intended_type=intended_type,
        intended_params=dict(intended_params),
        injection_status=InjectionStatus.SKIPPED,
        requested_at=time.time(),
        seed=seed,
        attempt_index=attempt_index,
    )


def seal(pending: PendingFaultEvent) -> FaultEvent:
    """Convert a completed PendingFaultEvent into an immutable FaultEvent.

    The one and only place a frozen FaultEvent is constructed from live
    dispatch state. After this call, nothing — including the instrumentation
    code itself — can alter the record. If a field was wrong when `seal()`
    was called, it is wrong forever, which is the correct failure mode for
    evidence: a bug that mis-set a field should be visible and fixed, not
    quietly patchable after the fact.
    """
    if not isinstance(pending, PendingFaultEvent):
        raise TypeError(
            f"seal() requires a PendingFaultEvent, got {type(pending).__name__}"
        )
